'use strict';

/* Disciplinary Action printouts (PDF) and the report workbook (Excel). */
const fs = require('fs');
const path = require('path');
const PDFDocument = require('pdfkit');
const ExcelJS = require('exceljs');
const config = require('../../config');
const { dmy: formatDisplayDate } = require('./disciplinary.format');

const LOGO = path.join(config.publicDir, 'assets', 'navy-logo.png');
const INK = '#1d2939';
const MUTED = '#556070';
const BLUE = '#0074a8';
const LINE = '#d3d7db';
const STRIPE = '#f5f7f9';
const d = (v) => formatDisplayDate(v) || '-';
const t = (v) => (v === null || v === undefined || v === '' ? '-' : String(v));
const nameOf = (c) => `${c.rate ? `${c.rate} ` : ''}${c.name}`;

function newDoc(layout) {
  return new PDFDocument({ size: 'A4', layout, margins: { top: 32, bottom: 40, left: 32, right: 32 }, bufferPages: true });
}

function finish(doc, generatedBy) {
  const stamp = `${new Date().toISOString().replace('T', ' ').slice(0, 16)} UTC`;
  const range = doc.bufferedPageRange();
  for (let i = 0; i < range.count; i += 1) {
    doc.switchToPage(range.start + i);
    const m = doc.page.margins.left;
    const w = doc.page.width - m * 2;
    const y = doc.page.height - 28;
    doc.font('Helvetica').fontSize(7.5).fillColor(MUTED)
      .text(`RESTRICTED — Nigerian Navy CIRERMS${generatedBy ? ` | Generated by: ${generatedBy}` : ''} | ${stamp}`, m, y, { width: w * 0.75, lineBreak: false })
      .text(`Page ${i + 1} of ${range.count}`, m, y, { width: w, align: 'right', lineBreak: false });
  }
  return new Promise((resolve, reject) => {
    const chunks = [];
    doc.on('data', (c) => chunks.push(c));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);
    doc.end();
  });
}

function header(doc, title) {
  const m = doc.page.margins.left;
  const w = doc.page.width - m * 2;
  const y = doc.page.margins.top;
  if (fs.existsSync(LOGO)) { try { doc.image(LOGO, m, y - 4, { width: 42 }); } catch (_) { /* no logo */ } }
  doc.fillColor(INK).font('Helvetica-Bold').fontSize(13).text('NIGERIAN NAVY — CIRERMS', m + 52, y, { width: w - 52 });
  doc.fillColor(MUTED).font('Helvetica').fontSize(8.5).text('Centralised Integrated Ratings Electronic Records Management System', m + 52, y + 16, { width: w - 52 });
  doc.fillColor(BLUE).font('Helvetica-Bold').fontSize(11).text(title, m + 52, y + 30, { width: w - 52 });
  doc.moveTo(m, y + 50).lineTo(doc.page.width - m, y + 50).lineWidth(1.2).strokeColor(BLUE).stroke();
  doc.y = y + 58;
}

/** Heading facts, two to a row: [[label, value], ...]. */
function meta(doc, pairs, perRow = 3) {
  const m = doc.page.margins.left;
  const w = (doc.page.width - m * 2) / perRow;
  for (let i = 0; i < pairs.length; i += perRow) {
    const y = doc.y;
    let h = 12;
    pairs.slice(i, i + perRow).forEach(([k, v], j) => {
      const x = m + j * w;
      doc.font('Helvetica-Bold').fontSize(7.5).fillColor(MUTED).text(k.toUpperCase(), x, y, { width: w - 8, lineBreak: false });
      doc.font('Helvetica').fontSize(9).fillColor(INK).text(t(v), x, y + 10, { width: w - 8 });
      h = Math.max(h, 10 + doc.heightOfString(t(v), { width: w - 8 }) + 4);
    });
    doc.y = y + h + 4;
  }
  doc.y += 2;
}

function table(doc, cols, rows) {
  const m = doc.page.margins.left;
  const usable = doc.page.width - m * 2;
  const weight = cols.reduce((s, c) => s + c.w, 0);
  const widths = cols.map((c) => (c.w / weight) * usable);
  const limit = doc.page.height - doc.page.margins.bottom - 24;
  const head = () => {
    const y = doc.y;
    doc.rect(m, y, usable, 20).fill(BLUE);
    let x = m;
    cols.forEach((c, i) => {
      doc.fillColor('#faf9f0').font('Helvetica-Bold').fontSize(8).text(c.h, x + 4, y + 6, { width: widths[i] - 8, lineBreak: false });
      x += widths[i];
    });
    doc.y = y + 20;
  };
  head();
  if (!rows.length) {
    doc.fillColor(MUTED).font('Helvetica-Oblique').fontSize(8.5).text('No cases.', m, doc.y + 6, { width: usable, align: 'center' });
    doc.y += 26;
    return;
  }
  rows.forEach((row, ri) => {
    const cells = cols.map((c) => t(c.v(row)));
    doc.font('Helvetica').fontSize(8);
    let rh = 18;
    cells.forEach((s, i) => { rh = Math.max(rh, Math.min(doc.heightOfString(s, { width: widths[i] - 8 }) + 8, 70)); });
    if (doc.y + rh > limit) { doc.addPage(); head(); }
    const y = doc.y;
    if (ri % 2) doc.rect(m, y, usable, rh).fill(STRIPE);
    doc.moveTo(m, y + rh).lineTo(m + usable, y + rh).lineWidth(0.4).strokeColor(LINE).stroke();
    let x = m;
    cells.forEach((s, i) => {
      doc.fillColor(INK).font('Helvetica').fontSize(8).text(s, x + 4, y + 4, { width: widths[i] - 8, height: rh - 4, ellipsis: true });
      x += widths[i];
    });
    doc.y = y + rh;
  });
}

function signatures(doc, names) {
  const m = doc.page.margins.left;
  const usable = doc.page.width - m * 2;
  if (doc.y + 70 > doc.page.height - doc.page.margins.bottom - 24) doc.addPage();
  doc.y += 40;
  const w = usable / names.length;
  const y = doc.y;
  names.forEach((n, i) => {
    const x = m + i * w + 10;
    doc.moveTo(x, y).lineTo(x + w - 40, y).lineWidth(0.6).strokeColor(INK).stroke();
    doc.fillColor(MUTED).font('Helvetica').fontSize(8).text(n, x, y + 4, { width: w - 40 });
  });
  doc.y = y + 30;
}

async function pendingListPdf({ rows, offence, search, generatedBy }) {
  const doc = newDoc('landscape');
  header(doc, 'PENDING DISCIPLINARY CASES');
  meta(doc, [['Cases', String(rows.length)], ['As at', d(new Date())], ['Offence', offence || 'All'], ['Search', search || 'None']], 4);
  table(doc, [
    { h: 'Case', w: 1.55, v: (c) => c.caseNumber }, { h: 'Official No', w: 1, v: (c) => c.serviceNumber },
    { h: 'Name', w: 2.2, v: nameOf }, { h: 'Ship', w: 1.5, v: (c) => c.ship },
    { h: 'Offence', w: 1.8, v: (c) => c.offence }, { h: 'Incident', w: 1, v: (c) => d(c.incidentDate) },
    { h: 'What Happened', w: 3, v: (c) => c.what }, { h: 'Reported By', w: 1.8, v: (c) => c.reportedBy },
  ], rows);
  signatures(doc, ['Prepared By', 'Director of Personnel (Navy)']);
  return finish(doc, generatedBy);
}

const REPORT_COLS = [
  { h: 'Case', w: 1.55, v: (c) => c.caseNumber }, { h: 'Official No', w: 1, v: (c) => c.serviceNumber },
  { h: 'Name', w: 2.1, v: nameOf }, { h: 'Ship', w: 1.4, v: (c) => c.ship },
  { h: 'Offence', w: 1.7, v: (c) => c.offence }, { h: 'Incident', w: 1, v: (c) => d(c.incidentDate) },
  { h: 'Decided', w: 1, v: (c) => d(c.decisionDate) }, { h: 'Sanction', w: 1.3, v: (c) => c.sanction },
  { h: 'Decision', w: 2.4, v: (c) => c.decision }, { h: 'Authority', w: 1.6, v: (c) => c.authority },
];

async function reportPdf({ rows, labels, generatedBy }) {
  const doc = newDoc('landscape');
  header(doc, 'DISCIPLINARY REPORT');
  meta(doc, [['Period', labels.period], ['Offence', labels.offence], ['Sanction', labels.sanction], ['Ship', labels.ship], ['Rate', labels.rate], ['Cases', String(rows.length)]], 6);
  table(doc, REPORT_COLS, rows);
  signatures(doc, ['Prepared By', 'Director of Personnel (Navy)']);
  return finish(doc, generatedBy);
}

async function caseSheetPdf({ c, generatedBy }) {
  const doc = newDoc('portrait');
  header(doc, 'DISCIPLINARY CASE SHEET');
  meta(doc, [['Case Number', c.caseNumber], ['Status', c.status === 'pending' ? 'Pending' : c.status === 'concluded' ? 'Concluded' : 'Cancelled'],
    ['Official No', c.serviceNumber], ['Name', c.name.toUpperCase()], ['Rate', c.rate], ['Ship', c.ship]], 2);
  const rows = [['Offence', c.offence], ['Incident date', d(c.incidentDate)], ['What happened', c.what], ['Reported by', c.reportedBy],
    ['Opened', `${d(c.openedAt)}${c.openedBy ? ` by ${c.openedBy}` : ''}`]];
  if (c.status === 'concluded') rows.push(['Decision date', d(c.decisionDate)], ['Sanction', c.sanction], ['Decision', c.decision], ['Authority', c.authority]);
  else if (c.status === 'cancelled') rows.push(['Cancelled', `${d(c.cancelledAt)}${c.cancelledBy ? ` by ${c.cancelledBy}` : ''}`], ['Reason', c.cancelReason]);
  else rows.push(['Decision', 'Awaiting decision']);
  table(doc, [{ h: 'Item', w: 1, v: (r) => r[0] }, { h: 'Particulars', w: 3.2, v: (r) => r[1] }], rows);
  if (c.corrections && c.corrections.length) {
    doc.y += 10;
    doc.fillColor(BLUE).font('Helvetica-Bold').fontSize(9).text('CORRECTIONS', doc.page.margins.left, doc.y);
    doc.y += 4;
    table(doc, [{ h: 'Date', w: 1, v: (k) => d(k.at) }, { h: 'By', w: 1, v: (k) => k.by }, { h: 'Reason', w: 2, v: (k) => k.reason },
      { h: 'Changed', w: 3, v: (k) => k.changes.map(([f, a, b]) => `${f}: ${a || '-'} -> ${b || '-'}`).join('; ') }], c.corrections);
  }
  signatures(doc, c.status === 'concluded' ? ['Reporting Officer', 'Authority', 'Director of Personnel (Navy)'] : ['Reporting Officer', 'Commanding Officer']);
  return finish(doc, generatedBy);
}

async function reportWorkbook({ rows, labels, generatedBy }) {
  const wb = new ExcelJS.Workbook();
  wb.creator = generatedBy || 'CIRERMS';
  const ws = wb.addWorksheet('Disciplinary Report');
  ws.addRow(['Disciplinary Report']).font = { bold: true, size: 14 };
  ws.addRow([`Period: ${labels.period}`, `Offence: ${labels.offence}`, `Sanction: ${labels.sanction}`, `Ship: ${labels.ship}`, `Rate: ${labels.rate}`, `Cases: ${rows.length}`]);
  ws.addRow([]);
  const head = ws.addRow(['Case', 'Official No', 'Name', 'Rate', 'Ship', 'Offence', 'Incident Date', 'What Happened', 'Reported By', 'Decision Date', 'Sanction', 'Decision', 'Authority']);
  head.eachCell((cell) => {
    cell.font = { bold: true, color: { argb: 'FFFAF9F0' } };
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF0074A8' } };
  });
  rows.forEach((c) => ws.addRow([c.caseNumber, c.serviceNumber, c.name, c.rate, c.ship, c.offence, d(c.incidentDate), c.what, c.reportedBy, d(c.decisionDate), c.sanction, c.decision, c.authority]));
  [14, 14, 30, 24, 22, 30, 14, 44, 30, 14, 20, 44, 28].forEach((w, i) => { ws.getColumn(i + 1).width = w; });
  ws.views = [{ state: 'frozen', ySplit: 4 }];
  return Buffer.from(await wb.xlsx.writeBuffer());
}

module.exports = { pendingListPdf, reportPdf, caseSheetPdf, reportWorkbook };
