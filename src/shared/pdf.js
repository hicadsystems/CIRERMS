'use strict';

const fs = require('fs');
const path = require('path');
const PDFDocument = require('pdfkit');
const config = require('../config');
const { formatDisplayDate } = require('./dates');

const LOGO_PATH = path.join(config.publicDir, 'assets', 'navy-logo.png');

const COLOURS = {
  navyBlue: '#0074a8',
  teal: '#1caf9a',
  darkInk: '#1d2939',
  mutedInk: '#556070',
  border: '#d3d7db',
  rowStripe: '#f5f7f9',
  headerBg: '#0074a8',
};

function collectPdfBuffer(doc) {
  return new Promise((resolve, reject) => {
    const chunks = [];
    doc.on('data', (chunk) => chunks.push(chunk));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);
    doc.end();
  });
}

function drawOfficialHeader(doc, { title, subtitle }) {
  const margin = doc.page.margins.left;
  const pageWidth = doc.page.width - margin * 2;
  const startY = doc.page.margins.top;

  if (fs.existsSync(LOGO_PATH)) {
    try {
      doc.image(LOGO_PATH, margin, startY - 4, { width: 42 });
    } catch (_) {
      // Ignore logo decode failure
    }
  }

  doc
    .fillColor(COLOURS.darkInk)
    .font('Helvetica-Bold')
    .fontSize(13)
    .text('NIGERIAN NAVY — CIRERMS', margin + 52, startY, {
      width: pageWidth - 52,
      align: 'left',
    });

  doc
    .fillColor(COLOURS.mutedInk)
    .font('Helvetica')
    .fontSize(8.5)
    .text('Centralised Integrated Ratings Electronic Records Management System', margin + 52, startY + 16, {
      width: pageWidth - 52,
      align: 'left',
    });

  doc
    .fillColor(COLOURS.navyBlue)
    .font('Helvetica-Bold')
    .fontSize(11)
    .text(title, margin + 52, startY + 30, {
      width: pageWidth - 52,
      align: 'left',
    });

  if (subtitle) {
    doc
      .fillColor(COLOURS.mutedInk)
      .font('Helvetica')
      .fontSize(8.5)
      .text(subtitle, margin, startY + 48, {
        width: pageWidth,
        align: 'right',
      });
  }

  const ruleY = startY + 62;
  doc
    .moveTo(margin, ruleY)
    .lineTo(doc.page.width - margin, ruleY)
    .lineWidth(1.2)
    .strokeColor(COLOURS.navyBlue)
    .stroke();

  doc.y = ruleY + 10;
}

function stampPageFooters(doc, generatedBy) {
  const range = doc.bufferedPageRange();
  const stampDate = new Date().toISOString().replace('T', ' ').slice(0, 16) + ' UTC';
  for (let i = 0; i < range.count; i += 1) {
    doc.switchToPage(range.start + i);
    const margin = doc.page.margins.left;
    const footerY = doc.page.height - 28;
    const width = doc.page.width - margin * 2;

    doc
      .font('Helvetica')
      .fontSize(7.5)
      .fillColor(COLOURS.mutedInk)
      .text(
        `RESTRICTED — Nigerian Navy CIRERMS${generatedBy ? ` | Generated by: ${generatedBy}` : ''} | ${stampDate}`,
        margin,
        footerY,
        { width: width * 0.75, align: 'left', lineBreak: false }
      );

    doc
      .font('Helvetica')
      .fontSize(7.5)
      .fillColor(COLOURS.mutedInk)
      .text(`Page ${i + 1} of ${range.count}`, margin, footerY, {
        width,
        align: 'right',
        lineBreak: false,
      });
  }
}

function drawTable(doc, columns, rows) {
  const margin = doc.page.margins.left;
  const usableWidth = doc.page.width - margin * 2;
  const totalWeight = columns.reduce((sum, c) => sum + (c.weight || 1), 0);
  const colWidths = columns.map((c) => ((c.weight || 1) / totalWeight) * usableWidth);
  const bottomLimit = doc.page.height - doc.page.margins.bottom - 22;

  const renderHeader = () => {
    const y = doc.y;
    const headerHeight = 20;
    doc.rect(margin, y, usableWidth, headerHeight).fill(COLOURS.headerBg);
    let x = margin;
    columns.forEach((col, idx) => {
      doc
        .fillColor('#ffffff')
        .font('Helvetica-Bold')
        .fontSize(8)
        .text(col.header, x + 5, y + 6, {
          width: colWidths[idx] - 10,
          align: col.align || 'left',
          lineBreak: false,
        });
      x += colWidths[idx];
    });
    doc.y = y + headerHeight;
  };

  renderHeader();

  if (!rows || rows.length === 0) {
    const y = doc.y;
    doc.rect(margin, y, usableWidth, 22).strokeColor(COLOURS.border).lineWidth(0.5).stroke();
    doc
      .fillColor(COLOURS.mutedInk)
      .font('Helvetica-Oblique')
      .fontSize(8.5)
      .text('No records available.', margin + 8, y + 6, { width: usableWidth - 16, align: 'center' });
    doc.y = y + 26;
    return;
  }

  rows.forEach((row, rowIndex) => {
    const cellTexts = columns.map((col) => {
      const raw = typeof col.value === 'function' ? col.value(row, rowIndex) : row[col.key];
      return raw == null || raw === '' ? '-' : String(raw);
    });

    doc.font('Helvetica').fontSize(8);
    let rowHeight = 18;
    cellTexts.forEach((txt, idx) => {
      const h = doc.heightOfString(txt, { width: colWidths[idx] - 10 }) + 8;
      if (h > rowHeight) rowHeight = Math.min(h, 54);
    });

    if (doc.y + rowHeight > bottomLimit) {
      doc.addPage();
      renderHeader();
    }

    const y = doc.y;
    if (rowIndex % 2 === 1) {
      doc.rect(margin, y, usableWidth, rowHeight).fill(COLOURS.rowStripe);
    }
    doc
      .moveTo(margin, y + rowHeight)
      .lineTo(margin + usableWidth, y + rowHeight)
      .lineWidth(0.4)
      .strokeColor(COLOURS.border)
      .stroke();

    let x = margin;
    cellTexts.forEach((txt, idx) => {
      doc
        .fillColor(COLOURS.darkInk)
        .font('Helvetica')
        .fontSize(8)
        .text(txt, x + 5, y + 4, {
          width: colWidths[idx] - 10,
          height: rowHeight - 4,
          align: columns[idx].align || 'left',
          ellipsis: true,
        });
      x += colWidths[idx];
    });

    doc.y = y + rowHeight;
  });
}

/**
 * Build Landscape A4 PDF for Current or Former Ratings List (used for PDF export & Print Report).
 */
async function buildRatingsListPdf({ status, rows, search = '', generatedBy = '' }) {
  const doc = new PDFDocument({
    size: 'A4',
    layout: 'landscape',
    margins: { top: 32, bottom: 36, left: 32, right: 32 },
    bufferPages: true,
  });

  const title = status === 'former' ? 'FORMER RATINGS NOMINAL ROLL' : 'CURRENT RATINGS NOMINAL ROLL';
  const filterNote = search
    ? `Total Matching Records: ${rows.length} | Filter: "${search}"`
    : `Total Records: ${rows.length}`;

  drawOfficialHeader(doc, { title, subtitle: filterNote });

  const columns = status === 'former'
    ? [
        { header: 'S/N', weight: 0.5, value: (_, i) => i + 1 },
        { header: 'Official No.', key: 'service_number', weight: 1.2 },
        { header: 'Fullname', key: 'full_name', weight: 2.4 },
        { header: 'Rate', key: 'rate_name', weight: 2.0 },
        { header: 'Exit Type', key: 'exit_type_name', weight: 1.6 },
        { header: 'Exit Date', weight: 1.2, value: (r) => formatDisplayDate(r.exit_date) },
        { header: 'Branch', key: 'branch_name', weight: 1.5 },
      ]
    : [
        { header: 'S/N', weight: 0.5, value: (_, i) => i + 1 },
        { header: 'Official No.', key: 'service_number', weight: 1.2 },
        { header: 'Full Name', key: 'full_name', weight: 2.5 },
        { header: 'Rate', key: 'rate_name', weight: 2.1 },
        { header: 'Current Ship', key: 'current_ship_name', weight: 1.8 },
        { header: 'Branch', key: 'branch_name', weight: 1.5 },
        { header: 'Command', key: 'command_name', weight: 1.8 },
      ];

  drawTable(doc, columns, rows);
  stampPageFooters(doc, generatedBy);

  return collectPdfBuffer(doc);
}

/**
 * Build Portrait A4 PDF for a single sub-record tab (Advancement, Drafting, Training, Education).
 */
async function buildRatingTabPdf({ rating, tabTitle, columns, rows, generatedBy = '' }) {
  const doc = new PDFDocument({
    size: 'A4',
    layout: 'portrait',
    margins: { top: 34, bottom: 38, left: 34, right: 34 },
    bufferPages: true,
  });

  const fullName = [rating.surname, rating.first_name, rating.middle_name].filter(Boolean).join(' ');
  drawOfficialHeader(doc, {
    title: `${tabTitle.toUpperCase()} RECORD`,
    subtitle: `${rating.service_number} — ${fullName} (${rating.rate_name || 'Unrated'})`,
  });

  drawTable(doc, columns, rows);
  stampPageFooters(doc, generatedBy);

  return collectPdfBuffer(doc);
}

function drawKeyValueGrid(doc, sectionTitle, pairs) {
  const margin = doc.page.margins.left;
  const usableWidth = doc.page.width - margin * 2;
  const bottomLimit = doc.page.height - doc.page.margins.bottom - 30;

  if (doc.y + 48 > bottomLimit) {
    doc.addPage();
  }

  doc
    .rect(margin, doc.y, usableWidth, 17)
    .fill('#e9eff4');
  doc
    .fillColor(COLOURS.navyBlue)
    .font('Helvetica-Bold')
    .fontSize(8.5)
    .text(sectionTitle.toUpperCase(), margin + 6, doc.y + 4, {
      width: usableWidth - 12,
      lineBreak: false,
    });
  doc.y += 22;

  const colWidth = usableWidth / 2;
  for (let i = 0; i < pairs.length; i += 2) {
    if (doc.y + 18 > bottomLimit) {
      doc.addPage();
    }
    const rowY = doc.y;
    const left = pairs[i];
    const right = pairs[i + 1];

    const drawPair = (pair, offsetX) => {
      if (!pair) return 14;
      const label = `${pair[0]}:`;
      const val = pair[1] == null || pair[1] === '' ? '-' : String(pair[1]);
      doc
        .fillColor(COLOURS.mutedInk)
        .font('Helvetica-Bold')
        .fontSize(8)
        .text(label, offsetX, rowY, { width: 95, lineBreak: false });
      const valWidth = colWidth - 102;
      doc
        .fillColor(COLOURS.darkInk)
        .font('Helvetica')
        .fontSize(8)
        .text(val, offsetX + 96, rowY, { width: valWidth });
      return Math.max(14, doc.heightOfString(val, { width: valWidth }) + 4);
    };

    const h1 = drawPair(left, margin);
    const h2 = drawPair(right, margin + colWidth);
    doc.y = rowY + Math.max(h1, h2);
  }

  doc.y += 6;
}

/**
 * Build full Portrait A4 Personnel Dossier PDF for a single rating.
 */
async function buildRatingDossierPdf({ rating, children, generatedBy = '' }) {
  const doc = new PDFDocument({
    size: 'A4',
    layout: 'portrait',
    margins: { top: 34, bottom: 38, left: 34, right: 34 },
    bufferPages: true,
  });

  const fullName = [rating.surname, rating.first_name, rating.middle_name].filter(Boolean).join(' ');
  drawOfficialHeader(doc, {
    title: `PERSONNEL DOSSIER — ${rating.service_number}`,
    subtitle: `${fullName} | Status: ${String(rating.status || 'current').toUpperCase()}`,
  });

  // Optional passport photo in top-right summary box if available on disk
  if (rating.passport_photo_path) {
    const photoDiskPath = path.join(config.uploads.photosDir, path.basename(rating.passport_photo_path));
    if (fs.existsSync(photoDiskPath)) {
      try {
        const photoX = doc.page.width - doc.page.margins.right - 68;
        doc.image(photoDiskPath, photoX, doc.y, { fit: [64, 76], align: 'right' });
      } catch (_) {
        // Ignore corrupt image so PDF export still succeeds
      }
    }
  }

  drawKeyValueGrid(doc, '1. Basic Details', [
    ['Official Number', rating.service_number],
    ['Rate', rating.rate_name],
    ['Title', rating.title_name],
    ['Status', String(rating.status || '').toUpperCase()],
    ['Surname', rating.surname],
    ['First Name', rating.first_name],
    ['Middle Name', rating.middle_name],
    ['Maiden Name', rating.maiden_name],
    ['Gender', rating.gender_name],
    ['Date of Birth', formatDisplayDate(rating.date_of_birth)],
    ['Marital Status', rating.marital_status_name],
    ['Married to Military', rating.married_to_military_personnel],
    ['Religion', rating.religion_name],
    ['Denomination', rating.religion_denomination_name],
    ['Tribe', rating.tribe_name],
    ['Current Ship', rating.current_ship_name],
  ]);

  drawKeyValueGrid(doc, '2. Contact & Identification', [
    ['State of Origin', rating.state_name],
    ['Local Government', rating.local_government_name],
    ['Geo-Political Zone', rating.geo_political_zone_name],
    ['Place of Birth', rating.place_of_birth],
    ['Mother Base', rating.mother_base_name],
    ['Phone', rating.phone],
    ['Email Address', rating.email_address],
    ['Home Address', rating.home_address],
    ['ID Type', rating.identification_type_name],
    ['Identity Number', rating.identity_number],
    ['Driver License No.', rating.driver_license_number],
    ['License Expiry', formatDisplayDate(rating.driver_license_expiry_date)],
  ]);

  drawKeyValueGrid(doc, '3. Health Information', [
    ['Weight (kg)', rating.weight_kg],
    ['Height (m)', rating.height_m],
    ['Chest (cm)', rating.chest_cm],
    ['Blood Group', rating.blood_group_name],
    ['Genotype', rating.blood_genotype_name],
    ['Hair Color', rating.hair_color_name],
    ['Eye Color', rating.eye_color_name],
    ['Complexion', rating.complexion_name],
    ['Tribal Mark', rating.tribal_mark ? 'Yes' : 'No'],
    ['Disability', rating.disability_name],
    ['Disability Comment', rating.disability_comment],
    ['Hobbies', rating.hobbies],
  ]);

  drawKeyValueGrid(doc, '4. Official Service Details', [
    ['Branch', rating.branch_name],
    ['Command', rating.command_name],
    ['Staff Branch', rating.staff_branch_name],
    ['Specialisation', rating.specialisation_name],
    ['Entry Mode', rating.entry_mode_name],
    ['Date Employed', formatDisplayDate(rating.date_employed)],
    ['Seniority Date', formatDisplayDate(rating.seniority_date)],
    ['Exit Type', rating.exit_type_name],
    ['Exit Date', formatDisplayDate(rating.exit_date)],
    ['Exit Reason', rating.exit_reason],
  ]);

  const sections = [
    {
      title: '5. Next of Kin',
      rows: children.nextOfKin || [],
      cols: [
        { header: 'First Name', key: 'first_name', weight: 1.5 },
        { header: 'Last Name', key: 'last_name', weight: 1.5 },
        { header: 'Mobile Number', key: 'mobile_number', weight: 1.4 },
        { header: 'Next of Kin Type', key: 'next_of_kin_type_name', weight: 1.2 },
      ],
    },
    {
      title: '6. Spouse & Children',
      rows: [
        ...(children.spouse || []).map((s) => ({ relation: 'Spouse', ...s })),
        ...(children.children || []).map((c) => ({ relation: 'Child', ...c })),
      ],
      cols: [
        { header: 'Relation', key: 'relation', weight: 0.9 },
        { header: 'Name', key: 'name', weight: 2.0 },
        { header: 'Phone Number', key: 'phone_number', weight: 1.3 },
        { header: 'Email Address', key: 'email_address', weight: 1.8 },
      ],
    },
    {
      title: '7. Advancement History',
      rows: children.advancement || [],
      cols: [
        { header: 'Rate', key: 'rate_name', weight: 1.8 },
        { header: 'Start Date', weight: 1.1, value: (r) => formatDisplayDate(r.start_date) },
        { header: 'End Date', weight: 1.1, value: (r) => formatDisplayDate(r.end_date) },
        { header: 'Decoration', key: 'decoration', weight: 1.4 },
        { header: 'Authority', key: 'authority', weight: 1.4 },
        { header: 'GCB No.', key: 'gcbno', weight: 1.0 },
      ],
    },
    {
      title: '8. Drafting History',
      rows: children.drafting || [],
      cols: [
        { header: 'Ship / Unit', key: 'ship_name', weight: 1.8 },
        { header: 'Rate', key: 'rate_name', weight: 1.6 },
        { header: 'Start Date', weight: 1.1, value: (r) => formatDisplayDate(r.start_date) },
        { header: 'End Date', weight: 1.1, value: (r) => (r.end_date ? formatDisplayDate(r.end_date) : 'Present') },
        { header: 'Remarks', key: 'remarks', weight: 2.0 },
      ],
    },
    {
      title: '9. Training & Education',
      rows: [
        ...(children.training || []).map((t) => ({ kind: 'Training', ...t })),
        ...(children.education || []).map((e) => ({ kind: 'Education', ...e })),
      ],
      cols: [
        { header: 'Type', key: 'kind', weight: 0.9 },
        { header: 'Institution', key: 'institution', weight: 2.2 },
        { header: 'Qualification', key: 'qualification', weight: 1.7 },
        { header: 'Class', key: 'classification', weight: 1.0 },
        { header: 'Period', weight: 1.5, value: (r) => `${formatDisplayDate(r.start_date) || '?'} – ${formatDisplayDate(r.end_date) || 'Present'}` },
      ],
    },
    {
      title: '10. Languages',
      rows: children.language || [],
      cols: [
        { header: 'Language', key: 'language_name', weight: 2.2 },
        { header: 'Read', weight: 1, value: (r) => (r.can_read ? 'Yes' : 'No') },
        { header: 'Write', weight: 1, value: (r) => (r.can_write ? 'Yes' : 'No') },
        { header: 'Speak', weight: 1, value: (r) => (r.can_speak ? 'Yes' : 'No') },
      ],
    },
  ];

  for (const sec of sections) {
    if (doc.y + 52 > doc.page.height - doc.page.margins.bottom - 24) {
      doc.addPage();
    }
    doc
      .fillColor(COLOURS.navyBlue)
      .font('Helvetica-Bold')
      .fontSize(9)
      .text(sec.title.toUpperCase(), doc.page.margins.left, doc.y);
    doc.y += 4;
    drawTable(doc, sec.cols, sec.rows);
    doc.y += 8;
  }

  stampPageFooters(doc, generatedBy);
  return collectPdfBuffer(doc);
}

